#!/usr/bin/env python3
"""
Phase B converter: GR00T-exporter per-session datasets -> ONE lerobot-native
v3 dataset with a single unified `action` column, consumable by lerobot-train
ACT (`--policy.type=act`).

Source: /lambdafs/shaurya/g1_sonic_system1/data/g1_raw_full  (5 tasks, 40
session dirs; each session is its own single-episode v3.0 dataset). Only
sessions whose parquet contains `action.token_state` are included (the SONIC
latent target only exists for 3 of the 5 tasks; see action_layout.json).

Target schema (per action_layout.json, endorsed Option A):
  action[78]            = concat(action.token_state[64], zeros[14])   float32
                          (14 hand dims zeroed; identical interface to GR00T SFT)
  observation.state[36] = observation.state.robot_q_current           float32
                          (7 root pose + 29 body joints; task-invariant)
  observation.images.head_cam / left_wrist_cam / right_wrist_cam
                        = native 480x640x3 videos, re-encoded by lerobot

Writes an episode_mapping.json sidecar (episode_index -> source session /
task / n_frames / instruction) so a shared eval_split (regenerated by the
coordinator) maps onto this dataset's episode indices.

No GPU. Run inside the `lerobot` conda env.
"""
from __future__ import annotations

import argparse
import glob
import json
import logging
import os
from pathlib import Path

import numpy as np
import pandas as pd

logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
log = logging.getLogger("bB_convert")

TOKEN_COL = "action.token_state"
STATE_COL = "observation.state.robot_q_current"
CAMS = ["head_cam", "left_wrist_cam", "right_wrist_cam"]
TOKEN_DIM = 64
HAND_DIM = 14
STATE_DIM = 36
IMG_H, IMG_W = 480, 640
FPS = 30
ROBOT_TYPE = "unitree_g1"

FEATURES = {
    "observation.state": {
        "dtype": "float32",
        "shape": (STATE_DIM,),
        "names": {"axes": [f"q_{i}" for i in range(STATE_DIM)]},
    },
    "action": {
        "dtype": "float32",
        "shape": (TOKEN_DIM + HAND_DIM,),
        "names": {
            "axes": [f"motion_token_{i}" for i in range(TOKEN_DIM)]
            + [f"left_hand_{i}" for i in range(7)]
            + [f"right_hand_{i}" for i in range(7)]
        },
    },
}
for _cam in CAMS:
    FEATURES[f"observation.images.{_cam}"] = {
        "dtype": "video",
        "shape": (IMG_H, IMG_W, 3),
        "names": ["height", "width", "channels"],
    }

def find_sessions(raw_root: Path):
    """Return sorted [(task, session_name, session_dir)] deterministically."""
    out = []
    for task in sorted(os.listdir(raw_root)):
        tdir = raw_root / task
        if not tdir.is_dir():
            continue
        for sess in sorted(os.listdir(tdir)):
            sdir = tdir / sess
            if (sdir / "meta" / "info.json").exists():
                out.append((task, sess, sdir))
    return out

def load_session_parquet(sdir: Path) -> pd.DataFrame | None:
    files = sorted(glob.glob(str(sdir / "data" / "chunk-*" / "file-*.parquet")))
    if not files:
        return None
    return pd.concat([pd.read_parquet(f) for f in files], ignore_index=True)

def session_instruction(sdir: Path, df: pd.DataFrame) -> str:
    tp = sdir / "meta" / "tasks.parquet"
    if tp.exists():
        tdf = pd.read_parquet(tp)
        if "task" in tdf.columns and len(tdf) > 0:

            if "task_index" in df.columns and "task_index" in tdf.columns:
                ti = int(df["task_index"].iloc[0])
                row = tdf[tdf["task_index"] == ti]
                if len(row) > 0:
                    return str(row["task"].iloc[0])
            return str(tdf["task"].iloc[0])
    return sdir.parent.name

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--raw-root", default="/lambdafs/shaurya/g1_sonic_system1/data/g1_raw_full")
    ap.add_argument("--out-root", default="/lambdafs/shaurya/g1_sonic_system1/data/g1_act_lerobot")
    ap.add_argument("--repo-id", default="shaurya/g1_sonic_act")
    ap.add_argument("--video-backend", default="pyav")
    ap.add_argument("--limit-episodes", type=int, default=0, help="debug: stop after N episodes (0=all)")
    args = ap.parse_args()

    import decord
    from lerobot.datasets import LeRobotDataset, LeRobotDatasetMetadata

    raw_root = Path(args.raw_root)
    out_root = Path(args.out_root)
    if out_root.exists() and any(out_root.iterdir()):
        raise SystemExit(f"Output {out_root} already exists and is non-empty. Refusing to overwrite.")

    sessions = find_sessions(raw_root)
    log.info("Found %d session dirs under %s", len(sessions), raw_root)

    ds = LeRobotDataset.create(
        repo_id=args.repo_id,
        fps=FPS,
        features=FEATURES,
        root=str(out_root),
        robot_type=ROBOT_TYPE,
        use_videos=True,
        video_backend=args.video_backend,
    )

    mapping = []
    ep_idx = 0
    included_tasks = {}
    skipped = []

    for task, sess, sdir in sessions:
        df = load_session_parquet(sdir)
        if df is None:
            skipped.append((task, sess, "no-parquet"))
            continue
        if TOKEN_COL not in df.columns:
            skipped.append((task, sess, "no-token_state"))
            continue
        if STATE_COL not in df.columns:
            skipped.append((task, sess, "no-robot_q_current"))
            continue
        vids = {}
        ok = True
        for cam in CAMS:
            vp = sorted(glob.glob(str(sdir / "videos" / f"observation.images.{cam}" / "chunk-*" / "file-*.mp4")))
            if not vp:
                ok = False
                break
            vids[cam] = vp[0]
        if not ok:
            skipped.append((task, sess, "missing-video"))
            continue

        import decord

        n = len(df)
        tok = np.stack(df[TOKEN_COL].to_numpy()).astype(np.float32)
        rqc = np.stack(df[STATE_COL].to_numpy()).astype(np.float32)
        assert tok.shape == (n, TOKEN_DIM), f"{sess}: token shape {tok.shape}"
        assert rqc.shape == (n, STATE_DIM), f"{sess}: state shape {rqc.shape}"
        assert np.isfinite(tok).all() and np.isfinite(rqc).all(), f"{sess}: non-finite values"

        readers = {cam: decord.VideoReader(vids[cam]) for cam in CAMS}
        for cam, vr in readers.items():
            if len(vr) != n:
                raise SystemExit(f"{sess}/{cam}: video frames {len(vr)} != parquet rows {n}")

        instr = session_instruction(sdir, df)
        zeros14 = np.zeros((HAND_DIM,), dtype=np.float32)

        for i in range(n):
            frame = {
                "observation.state": rqc[i],
                "action": np.concatenate([tok[i], zeros14]).astype(np.float32),
                "task": instr,
            }
            for cam in CAMS:
                frame[f"observation.images.{cam}"] = readers[cam][i].asnumpy()
            ds.add_frame(frame)
        ds.save_episode()

        mapping.append({
            "episode_index": ep_idx,
            "task": task,
            "source_session": sess,
            "n_frames": int(n),
            "instruction": instr,
        })
        included_tasks[task] = included_tasks.get(task, 0) + 1
        log.info("[ep %d] %s / %s : %d frames", ep_idx, task, sess, n)
        ep_idx += 1
        del readers
        if args.limit_episodes and ep_idx >= args.limit_episodes:
            log.warning("Stopping early after %d episodes (debug limit).", ep_idx)
            break

    ds.finalize()

    with open(out_root / "episode_mapping.json", "w") as f:
        json.dump({
            "repo_id": args.repo_id,
            "raw_root": str(raw_root),
            "action_dim": TOKEN_DIM + HAND_DIM,
            "action_layout": {"motion_token": [0, 64], "left_hand_joints": [64, 71], "right_hand_joints": [71, 78]},
            "hands_zeroed": True,
            "state_dim": STATE_DIM,
            "state_source": STATE_COL,
            "fps": FPS,
            "total_episodes": ep_idx,
            "included_task_counts": included_tasks,
            "skipped": [{"task": t, "session": s, "reason": r} for (t, s, r) in skipped],
            "episodes": mapping,
        }, f, indent=2)

    log.info("DONE. episodes=%d  included_tasks=%s", ep_idx, included_tasks)
    if skipped:
        log.info("skipped %d sessions:", len(skipped))
        for t, s, r in skipped:
            log.info("   skip %s/%s (%s)", t, s, r)

    meta = LeRobotDatasetMetadata(args.repo_id, root=str(out_root))
    log.info("VALIDATE: total_episodes=%d total_frames=%d features_action_shape=%s",
             meta.total_episodes, meta.total_frames, meta.features["action"]["shape"])
    for e in range(meta.total_episodes):
        dp = meta.root / meta.get_data_file_path(e)
        if not dp.exists():
            raise SystemExit(f"missing parquet ep {e}: {dp}")
        for vk in meta.video_keys:
            vp = meta.root / meta.get_video_file_path(e, vk)
            if not vp.exists():
                raise SystemExit(f"missing video ep {e} {vk}: {vp}")
    log.info("VALIDATE OK: all parquet + video files present for %d episodes.", meta.total_episodes)

if __name__ == "__main__":
    main()
